# 1. DATA CLEANING & PREPARATION
# Filter to successful runs where the target building was evaluable
model_df = df[(df['Status'] == 'SUCCESS') & (df['has_target_building'] == True)].copy()

features = [
    'boarded_up', 'smashed_glass', 'roof_damage', 'graffiti',
    'fixed_grilles', 'internal_debris', 'facade_decay', 'unmanaged_weeds',
    'obsolete_signage', 'external_padlocks', 'threshold_debris',
    'deterrent_signage', 'exposed_wiring', 'infilled_apertures'
]

# Ensure binary types
for feat in features:
    if feat in model_df.columns:
        model_df[feat] = model_df[feat].fillna(0).astype(int)
model_df['Ground_Truth'] = model_df['Ground_Truth'].astype(int)

print(f"Dataset Size for Analysis: {len(model_df)} properties")
print("Ground Truth Distribution:")
print(model_df['Ground_Truth'].value_counts())

# 2. BOOTSTRAPPING (1,000 ITERATIONS)
n_iterations = 1000
boot_coefs = []
np.random.seed(42)

print(f"\nRunning {n_iterations:,} Bootstrap Iterations...")
for _ in range(n_iterations):
    boot_samp = model_df.sample(n=len(model_df), replace=True)

    # Drop features with zero variance in this specific bootstrap sample
    valid_features = [f for f in features if boot_samp[f].nunique() > 1]

    X_boot = sm.add_constant(boot_samp[valid_features])
    y_boot = boot_samp['Ground_Truth']

    try:
        model = sm.Logit(y_boot, X_boot).fit(disp=False, method='bfgs')
        boot_coefs.append(model.params)
    except Exception:
        continue

# 3. COMPUTE FINAL BOOTSTRAPPED WEIGHTS
boot_df = pd.DataFrame(boot_coefs)
final_weights = boot_df.mean().fillna(0)

print("\n--- FINAL BOOTSTRAPPED WEIGHTS (Log-Odds) ---")
print(final_weights.sort_values(ascending=False).round(3))

# 4. PREDICTIONS & ROC OPTIMIZATION (YOUDEN'S J)
def calculate_log_odds(row):
    log_odds = final_weights.get('const', 0.0)
    for feat in features:
        if feat in final_weights:
            log_odds += row[feat] * final_weights[feat]
    return 1 / (1 + np.exp(-log_odds))

model_df['Final_Prob'] = model_df.apply(calculate_log_odds, axis=1)

fpr, tpr, thresholds = roc_curve(model_df['Ground_Truth'], model_df['Final_Prob'])
roc_auc = auc(fpr, tpr)

# Maximize Youden's J Index: J = Sensitivity + Specificity - 1
youden_j = tpr - fpr
optimal_idx = np.argmax(youden_j)
optimal_threshold = thresholds[optimal_idx]
optimal_sensitivity = tpr[optimal_idx]
optimal_specificity = 1 - fpr[optimal_idx]

print("\n--- THE OPTIMAL CONFIDENCE THRESHOLD (Youden's J) ---")
print(f"Optimal Threshold cutoff: {optimal_threshold * 100:.1f}%")
print(f"Vacant properties detected (Sensitivity): {optimal_sensitivity * 100:.1f}%")
print(f"Normal properties safely ignored (Specificity): {optimal_specificity * 100:.1f}%")
print(f"Model AUC Score: {roc_auc:.3f}")

# 5. CONFUSION MATRIX
model_df['Predicted_Class'] = (model_df['Final_Prob'] >= optimal_threshold).astype(int)
conf_matrix = confusion_matrix(model_df['Ground_Truth'], model_df['Predicted_Class'])

print("\n--- CONFUSION MATRIX ---")
