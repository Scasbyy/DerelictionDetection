from sklearn.metrics import roc_curve, confusion_matrix, auc

EXCEL_PATH = '/content/drive/MyDrive/StreetView/Gemini Test/Master_Vacancy_Extraction.xlsx'

print(f"Loading data from: {EXCEL_PATH}")
