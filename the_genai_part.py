OPTIMAL_THRESHOLD = 0.464 # 46.4% Youden's J Cutoff

def calculate_vacancy_prob(flags_dict, has_target):
    if not has_target:
        return 0.0, 0.0, "OCCUPIED_OR_NON_EVALUABLE"

    log_odds = MODEL_3_WEIGHTS['const']
    for feature, weight in MODEL_3_WEIGHTS.items():
        if feature == 'const': continue
        if flags_dict.get(feature, False):
            log_odds += weight

    probability = 1 / (1 + math.exp(-log_odds))
    status = "VACANT" if probability >= OPTIMAL_THRESHOLD else "OCCUPIED"
    return round(log_odds, 3), round(probability * 100, 2), status

