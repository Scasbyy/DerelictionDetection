def print_evaluation(model_name, y_true, y_prob, threshold):
    # Apply the optimal Youden's J threshold
    y_pred = (y_prob >= threshold).astype(int)
    cm = confusion_matrix(y_true, y_pred)

    # Extract hard numbers safely
    if cm.size == 4:
        tn, fp, fn, tp = cm.ravel()
    else: # Edge case fallback if perfect separation occurs in a tiny subset
        tn, fp, fn, tp = cm[0][0], 0, 0, 0

    # Calculate percentages
    sensitivity = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    specificity = tn / (tn + fp) if (tn + fp) > 0 else 0.0

    print(f"\n{'='*55}")
    print(f" {model_name.upper()} (Threshold: {threshold*100:.1f}%)")
    print(f"{'='*55}")
