print(f"False Positives (Normal classified as Vacant): {conf_matrix[0][1]}")
print(f"False Negatives (Vacant classified as Normal): {conf_matrix[1][0]}")
print(f"True Positives (Vacant classified as Vacant):  {conf_matrix[1][1]}")

