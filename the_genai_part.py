plt.plot(fpr, tpr, color='blue', lw=2, label=f'ROC curve (AUC = {roc_auc:.2f})')
plt.scatter([fpr[optimal_idx]], [tpr[optimal_idx]], color='red', s=80, zorder=5,
            label=f'Optimal Cutoff ({optimal_threshold:.2f})')
