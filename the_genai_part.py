def run_bootstrapped_model(df, features, name, n_iterations=1000):
    print(f"\nRunning 1,000 Bootstraps for {name}...")
    boot_coefs = []
    np.random.seed(42)

    for _ in range(n_iterations):
        boot_samp = df.sample(n=len(df), replace=True)
        # Drop features with zero variance in this specific bootstrap to avoid matrix errors
        valid_feats = [f for f in features if boot_samp[f].nunique() > 1]

        X_boot = sm.add_constant(boot_samp[valid_feats])
        y_boot = boot_samp['Ground_Truth']

        try:
            model = sm.Logit(y_boot, X_boot).fit(disp=False, method='bfgs')
            boot_coefs.append(model.params)
        except Exception:
            continue

    final_weights = pd.DataFrame(boot_coefs).mean().fillna(0)

    def get_prob(row):
        log_odds = final_weights.get('const', 0.0)
        for feat in features:
            if feat in final_weights:
                log_odds += row[feat] * final_weights[feat]
        return 1 / (1 + np.exp(-log_odds))

    probs = df.apply(get_prob, axis=1)

    fpr, tpr, thresholds = roc_curve(df['Ground_Truth'], probs)
    roc_auc = auc(fpr, tpr)

    # Youden's J threshold optimization
    opt_idx = np.argmax(tpr - fpr)
    opt_thresh = thresholds[opt_idx]

    return fpr, tpr, roc_auc, opt_idx, opt_thresh, final_weights

